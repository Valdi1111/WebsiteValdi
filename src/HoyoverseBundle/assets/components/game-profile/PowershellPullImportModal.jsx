import { useBackendApi } from "@GamesBundle/components/BackendApiContext";
import { CopyOutlined, CheckOutlined, SnippetsOutlined, WindowsOutlined } from "@ant-design/icons";
import { Modal, Input, Button, Typography, Space, Alert, Steps, App } from "antd";
import React, { useState } from "react";

const { Text } = Typography;

export default function PowershellPullImportModal({ open, profile, accountId, profileId, onClose, onImportStarted }) {
    const [url, setUrl] = useState("");
    const [loading, setLoading] = useState(false);
    const [copied, setCopied] = useState(false);
    const { message } = App.useApp();
    const api = useBackendApi();

    const resolvedProfileId = profile?.id ?? profileId;
    const scriptUrl = api.gameProfiles().getPowershellScriptUrl(profile?.game_id);
    const scriptCommand = `[Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12; Invoke-Expression (New-Object Net.WebClient).DownloadString("${scriptUrl}")`;

    const handleCopyCommand = () => {
        navigator.clipboard.writeText(scriptCommand).then(() => {
            setCopied(true);
            message.success("PowerShell command copied to clipboard!");
            setTimeout(() => setCopied(false), 2500);
        });
    };

    const handlePasteUrl = async () => {
        try {
            const text = await navigator.clipboard.readText();
            if (text) {
                setUrl(text.trim());
                message.success("URL pasted from clipboard!");
            }
        } catch {
            message.info("Please paste the URL manually into the text field.");
        }
    };

    const handleSubmit = () => {
        const cleanUrl = url.trim();
        if (!cleanUrl) {
            message.warning("Please enter the URL generated by the PowerShell script.");
            return;
        }

        if (!cleanUrl.includes("authkey=")) {
            message.error("The provided URL does not appear to contain the required authkey parameter.");
            return;
        }

        setLoading(true);
        api
            .withLoadingMessage({
                key: "import-powershell-pulls",
                loadingContent: "Queueing background import...",
                successContent: "Import queued successfully! Your pulls will be processed shortly.",
            })
            .gameProfiles()
            .importPowershellPulls(accountId, resolvedProfileId, { url: cleanUrl })
            .then((res) => {
                setUrl("");
                onImportStarted?.(res?.data?.operation || null);
                onClose();
            })
            .catch(() => {
                // Error already displayed by withLoadingMessage
            })
            .finally(() => {
                setLoading(false);
            });
    };

    return (
        <Modal
            title={
                <Space>
                    <WindowsOutlined style={{ color: "#1890ff" }} />
                    <span>Import Pulls via PowerShell{profile?.nickname || profile?.game_name ? ` - ${profile?.nickname || profile?.game_name}` : ""}</span>
                </Space>
            }
            open={open}
            onCancel={() => {
                setUrl("");
                onClose();
            }}
            width={640}
            footer={[
                <Button
                    key="cancel"
                    onClick={() => {
                        setUrl("");
                        onClose();
                    }}
                    disabled={loading}
                >
                    Cancel
                </Button>,
                <Button key="submit" type="primary" loading={loading} onClick={handleSubmit}>
                    Start Import
                </Button>,
            ]}
        >
            <Alert
                type="info"
                showIcon
                style={{ marginBottom: 20 }}
                title="How link extraction works"
                description="Honkai: Star Rail and other clients require an authentication key generated directly by the game client. This command reads your local session cache in read-only mode and automatically copies the URL to your clipboard."
            />

            <Steps
                orientation="vertical"
                size="small"
                current={url ? 2 : 1}
                items={[
                    {
                        title: "1. Open the in-game history screen",
                        content: (
                            <Text type="secondary">
                                Launch <strong>{profile?.game_name || "the game"}</strong> on your PC, press ESC, and open the <strong>Warp / Wish / Signal Search History</strong> screen in the Gacha menu.
                            </Text>
                        ),
                    },
                    {
                        title: "2. Run the command in PowerShell",
                        content: (
                            <div style={{ marginTop: 8 }}>
                                <Text type="secondary">
                                    Open <strong>Windows PowerShell</strong> on your PC and run the following command:
                                </Text>
                                <div
                                    style={{
                                        display: "flex",
                                        alignItems: "center",
                                        gap: 8,
                                        background: "#1e1e1e",
                                        padding: "8px 12px",
                                        borderRadius: 6,
                                        marginTop: 6,
                                        border: "1px solid #333",
                                    }}
                                >
                                    <code style={{ color: "#4ec9b0", flex: 1, wordBreak: "break-all", fontSize: 13 }}>
                                        {scriptCommand}
                                    </code>
                                    <Button
                                        size="small"
                                        type={copied ? "primary" : "default"}
                                        icon={copied ? <CheckOutlined /> : <CopyOutlined />}
                                        onClick={handleCopyCommand}
                                    >
                                        {copied ? "Copied!" : "Copy"}
                                    </Button>
                                </div>
                            </div>
                        ),
                    },
                    {
                        title: "3. Paste the extracted link",
                        content: (
                            <div style={{ marginTop: 8 }}>
                                <Text type="secondary">
                                    The script will extract the link containing your authkey and automatically copy it to your clipboard. Paste it below:
                                </Text>
                                <Space.Compact style={{ width: "100%", marginTop: 8 }}>
                                    <Input
                                        placeholder="https://public-operation-hkrpg-sg.hoyoverse.com/.../getGachaLog?authkey=..."
                                        value={url}
                                        onChange={(e) => setUrl(e.target.value)}
                                        allowClear
                                    />
                                    <Button icon={<SnippetsOutlined />} onClick={handlePasteUrl}>
                                        Paste
                                    </Button>
                                </Space.Compact>
                            </div>
                        ),
                    },
                ]}
            />
        </Modal>
    );
}
